// Version comes from the release tag in CI: -PversionName=1.2.3 -PversionCode=10203
val appVersionName = (project.findProperty("versionName") as String?) ?: "0.1.0-dev"
val appVersionCode = (project.findProperty("versionCode") as String?)?.toInt() ?: 1

// Release signing: from environment (CI secrets) or a local keystore.properties (git-ignored).
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(env: String, prop: String): String? =
    System.getenv(env)?.takeIf { it.isNotBlank() } ?: keystoreProps.getProperty(prop)

val releaseStoreFile = signingValue("SSOK_KEYSTORE_FILE", "storeFile")

